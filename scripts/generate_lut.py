"""Generate the synthesizable Q16 exp(-delta/16) ROM, round half up."""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]

def main():
    rows = ["// Generated by scripts/generate_lut.py; delta is Q4.4.",
            "// 指数查表：delta=最大logit-当前logit，8位无符号，真实差值=delta/16。",
            "// value=round(exp(-delta/16)*65536)，17位无符号；65536表示1。",
            "// 组合查表，无时钟、无状态；不指定映射为FPGA BRAM或ASIC SRAM。",
            "module exp_lut(input [7:0] delta, output reg [16:0] value);",
            "always @* begin", "case(delta)"]
    for delta in range(256):
        value = int(math.floor(math.exp(-delta/16.0)*65536+0.5))
        rows.append(f"8'd{delta}: value=17'd{value};")
    rows += ["default: value=0;", "endcase", "end", "endmodule", ""]
    (ROOT / "rtl/exp_lut.v").write_text("\n".join(rows), encoding="utf-8")

if __name__ == "__main__":
    main()
